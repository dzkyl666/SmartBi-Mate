-- ------------------------------------------------------------
-- 4. 订单事实表（核心业务表）
-- ------------------------------------------------------------
DROP TABLE IF EXISTS fact_order;
CREATE TABLE fact_order (
    order_id      BIGINT PRIMARY KEY COMMENT '订单ID',
    user_id       INT NOT NULL COMMENT '用户ID',
    product_id    INT NOT NULL COMMENT '商品ID',
    region_id     INT NOT NULL COMMENT '下单地区ID',
    quantity      INT NOT NULL COMMENT '购买数量',
    unit_price    DECIMAL(10,2) NOT NULL COMMENT '成交单价（快照）',
    order_amount  DECIMAL(12,2) NOT NULL COMMENT '订单金额 = quantity * unit_price',
    discount      DECIMAL(5,2) DEFAULT 0.00 COMMENT '折扣率（0.00~1.00，0表示无折扣）',
    pay_amount    DECIMAL(12,2) NOT NULL COMMENT '实付金额 = order_amount * (1-discount)',
    order_status  VARCHAR(10) NOT NULL COMMENT '订单状态（已完成/已取消/退款中）',
    order_date    DATE NOT NULL COMMENT '下单日期',
    pay_date      DATE DEFAULT NULL COMMENT '支付日期',
    FOREIGN KEY (user_id) REFERENCES dim_user(user_id),
    FOREIGN KEY (product_id) REFERENCES dim_product(product_id),
    FOREIGN KEY (region_id) REFERENCES dim_region(region_id)
) COMMENT='订单事实表';

